class FASComplaintGenerator:
    """Генератор жалоб в Федеральную антимонопольную службу РФ."""

    @classmethod
    def get_fas_authority(
        cls,
        customer_inn: Optional[str] = None,
        customer_address: Optional[str] = None,
        customer_name: Optional[str] = None,
    ) -> Tuple[str, str]:
        """Определяет наименование и адрес территориального органа ФАС России."""
        # 1. По первым двум цифрам ИНН
        if customer_inn and len(customer_inn) >= 2:
            region_code = customer_inn[:2]
            if region_code in _FAS_AUTHORITIES:
                return _FAS_AUTHORITIES[region_code]

        # 2. По ключевым словам в адресе или названии
        search_blob = f"{customer_address or ''} {customer_name or ''}".lower()
        if "красноярск" in search_blob:
            return _FAS_AUTHORITIES["24"]
        if "карели" in search_blob or "петрозаводск" in search_blob:
            return _FAS_AUTHORITIES["10"]
        if "москв" in search_blob:
            return _FAS_AUTHORITIES["77"]
        if "санкт-петербург" in search_blob or "петербург" in search_blob:
            return _FAS_AUTHORITIES["78"]
        if "самар" in search_blob:
            return _FAS_AUTHORITIES["63"]
        if "татарстан" in search_blob or "казан" in search_blob:
            return _FAS_AUTHORITIES["16"]
        if "новосибирск" in search_blob:
            return _FAS_AUTHORITIES["54"]
        if "свердловск" in search_blob or "екатеринбург" in search_blob:
            return _FAS_AUTHORITIES["66"]

        return (
            "Управление Федеральной антимонопольной службы по месту нахождения Заказчика (УФАС России)",
            "По территориальной подсудности Заказчика",
        )

    @classmethod
    def generate(
        cls,
        report: FullAnalysisReport,
        applicant_name: Optional[str] = None,
        applicant_inn: Optional[str] = None,
        applicant_contacts: Optional[str] = None,
    ) -> FASComplaint:
        """Формирует полную юридическую жалобу в ФАС по ст. 105 44-ФЗ."""
        summary = report.summary
        fas_name, fas_addr = cls.get_fas_authority(
            customer_inn=summary.customer_inn,
            customer_address=summary.customer_address,
            customer_name=summary.customer_name,
        )

        app_name = applicant_name or "Участник закупки"
        nmck_text = f"{summary.nmck_rubles:,.2f} ₽".replace(",", " ") if summary.nmck_rubles else "Не определена (по цене единицы)"

        episodes: List[FASComplaintEpisode] = []
        ep_num = 1

        # Анализ выявленных рисков для формирования эпизодов
        for r in report.risks:
            # Эпизод: Сроки поставки (24 часа или сверхкороткий срок)
            if r.category == RiskCategory.TIMING and r.severity == RiskSeverity.HIGH:
                episodes.append(
                    FASComplaintEpisode(
                        number=ep_num,
                        title=f"Нарушение правил описания объекта закупки и ограничение конкуренции: {r.title}",
                        violated_norms="ч. 1, 2 ст. 33 Федерального закона № 44-ФЗ, ст. 17 Федерального закона № 135-ФЗ «О защите конкуренции»",
                        circumstances=(
                            f"В проекте контракта / информационной карте Заказчиком установлено следующее условие о сроках исполнения обязательств:\n"
                            f"«{r.quote or r.description}».\n\n"
                            "Установление заведомо нереалистичного срока исполнения поставки специализированного медицинского оборудования "
                            "создает непреодолимые препятствия для участия добросовестных поставщиков и исключает возможность поставки "
                            "товара непосредственно от производителя либо через официальную дистрибьюторскую сеть с соблюдением температурных "
                            "и логистических регламентов."
                        ),
                        legal_argumentation=(
                            "Согласно ч. 2 ст. 33 Федерального закона № 44-ФЗ документация о закупке не должна содержать требования, "
                            "влекущие за собой ограничение количества участников закупки.\n"
                            "В силу ст. 17 Федерального закона № 135-ФЗ при проведении торгов запрещаются действия, которые приводят или могут "
                            "привести к недопущению, ограничению или устранению конкуренции, в том числе создание участнику торгов преимущественных условий.\n"
                            "В соответствии с правовой позицией Президиума Высшего Арбитражного Суда РФ (Постановление № 623/12), а также устойчивой "
                            "практикой ФАС России (решения ФАС России № 22/44/105/112, Московского УФАС № 077/06/106-1845/2023), установление "
                            "сроков поставки высокотехнологичной продукции, объективно исполнимых исключительно лицом, имеющим сформированный запас "
                            "на локальном складе в регионе Заказчика, свидетельствует о грубом нарушении принципа обеспечения конкуренции."
                        ),
                    )
                )
                ep_num += 1

            # Эпизод: Заточка под конкретного производителя (ТЗ / Оборудование)
            elif r.category == RiskCategory.TECHNICAL and r.severity in (RiskSeverity.HIGH, RiskSeverity.MEDIUM):
                bias_notes = ""
                if report.equipment:
                    eq = report.equipment[0]
                    bias_notes = f"\nХарактеристики, указывающие на ограничение эквивалентов: {', '.join(eq.key_specs[:6])}."

                episodes.append(
                    FASComplaintEpisode(
                        number=ep_num,
                        title=f"Нарушение требований ст. 33 Закона № 44-ФЗ: включение параметров под единственного производителя ({r.title})",
                        violated_norms="п. 1 ч. 1 ст. 33, ч. 2 ст. 33 Федерального закона № 44-ФЗ",
                        circumstances=(
                            f"В Техническом задании (Описании объекта закупки) Заказчик установил совокупность узких характеристик:\n"
                            f"«{r.quote or r.description}»{bias_notes}\n\n"
                            "Совокупности указанных параметров и конструктивных особенностей в точности соответствует исключительно продукция "
                            "ограниченной линейки одного производителя, в то время как изделия иных производителей, зарегистрированные в установленном "
                            "порядке Росздравнадзором и имеющие сопоставимое клиническое назначение, не могут быть предложены к поставке."
                        ),
                        legal_argumentation=(
                            "В соответствии с п. 1 ч. 1 ст. 33 Федерального закона № 44-ФЗ описание объекта закупки должно носить объективный характер. "
                            "В описании объекта закупки указываются функциональные, технические и качественные характеристики, эксплуатационные характеристики.\n"
                            "Заказчик не вправе устанавливать требования к товару, которые индивидуализируют товар одного конкретного изготовителя "
                            "и исключают возможность предложения эквивалентной продукции иных зарегистрированных производителей.\n"
                            "Согласно Обзору судебной практики применения законодательства РФ о контрактной системе (утв. Президиумом Верховного Суда РФ 28.06.2017), "
                            "включение заказчиком в документацию о закупке требований к закупаемому товару, которые свидетельствуют о его конкретном производителе, "
                            "в отсутствие объективной специфики потребностей заказчика, нарушает требования ч. 2 ст. 33 Закона № 44-ФЗ."
                        ),
                    )
                )
                ep_num += 1

            # Эпизод: Неустойки и пени (ПП РФ № 1042)
            elif r.category == RiskCategory.LEGAL and "1042" in (r.law_reference or r.title):
                episodes.append(
                    FASComplaintEpisode(
                        number=ep_num,
                        title=f"Нарушение порядка определения размера неустойки: {r.title}",
                        violated_norms="ч. 5, 7, 8 ст. 34 Федерального закона № 44-ФЗ, Постановление Правительства РФ № 1042 от 30.08.2017",
                        circumstances=(
                            f"В проекте государственного контракта Заказчик установил условие об ответственности сторон:\n"
                            f"«{r.quote or r.description}».\n\n"
                            "Указанный размер штрафа/пени прямо противоречит обязательным правилам определения размера штрафа и пени, "
                            "утвержденным Постановлением Правительства РФ № 1042."
                        ),
                        legal_argumentation=(
                            "Частями 5 и 7 статьи 34 Федерального закона № 44-ФЗ прямо установлено, что порядок определения размера пени и штрафов "
                            "устанавливается Правительством Российской Федерации. Данные нормы носят строго императивный характер.\n"
                            "Постановление Правительства РФ от 30.08.2017 № 1042 не допускает установления произвольных размеров ответственности, "
                            "превышающих либо противоречащих нормативно установленной шкале. Включение в проект контракта положений, искажающих "
                            "императивную шкалу ПП РФ № 1042, является грубым нарушением законодательства о контрактной системе."
                        ),
                    )
                )
                ep_num += 1

            # Эпизод: Незаконные требования к заявке (РУ в первой части / маркировка)
            elif r.category == RiskCategory.LEGAL and ("регистрационн" in r.title.lower() or "ру" in r.title.lower() or "заявк" in r.title.lower()):
                episodes.append(
                    FASComplaintEpisode(
                        number=ep_num,
                        title=f"Неправомерное требование документов и сведений в составе заявки: {r.title}",
                        violated_norms="ч. 2 ст. 48, ч. 6 ст. 43 Федерального закона № 44-ФЗ",
                        circumstances=(
                            f"В извещении о закупке Заказчиком установлено требование:\n«{r.quote or r.description}».\n\n"
                            "Требование предоставления регистрационных удостоверений, сертификатов или нанесения дополнительной нестандартной "
                            "маркировки с номерами контракта до момента поставки товара нарушает порядок подачи заявок."
                        ),
                        legal_argumentation=(
                            "В силу ч. 2 ст. 48 Закона № 44-ФЗ не допускается установление требований к содержанию заявки, не предусмотренных "
                            "законодательством РФ. Документы, подтверждающие соответствие товара (регистрационные удостоверения, декларации соответствия), "
                            "в силу прямого указания закона передаются Заказчику непосредственно при передаче товара, а не в составе первой части заявки."
                        ),
                    )
                )
                ep_num += 1

        # Если специфических нарушений не выделено, формируем общий базовый эпизод по ст. 33 44-ФЗ
        if not episodes:
            episodes.append(
                FASComplaintEpisode(
                    number=1,
                    title="Нарушение требований к объективному описанию объекта закупки (ст. 33 44-ФЗ)",
                    violated_norms="ч. 1, 2 ст. 33 Федерального закона № 44-ФЗ",
                    circumstances=(
                        f"По закупке №{summary.notice_number} Заказчиком установлены требования к характеристикам и условиям исполнения, "
                        "ограничивающие круг потенциальных поставщиков эквивалентной продукции."
                    ),
                    legal_argumentation=(
                        "Согласно ч. 2 ст. 33 Закона № 44-ФЗ документация о закупке не должна содержать требования к товарам, информации, "
                        "работам, услугам при условии, если такие требования влекут за собой ограничение количества участников закупки."
                    ),
                )
            )

        # Просительная часть (ПРОШУ)
        petitum = [
            f"Принять настоящую жалобу на положения извещения №{summary.notice_number} к рассмотрению в порядке ст. 105, 106 Федерального закона № 44-ФЗ.",
            f"Приостановить определение поставщика (подрядчика, исполнителя) по электронному аукциону №{summary.notice_number} в части заключения контракта до рассмотрения настоящей жалобы по существу.",
            f"Провести внеплановую камеральную проверку извещения и электронных документов закупки №{summary.notice_number} на предмет соответствия требованиям законодательства РФ о контрактной системе.",
            "Признать настоящую жалобу Заявителя обоснованной.",
            f"Выдать Заказчику ({summary.customer_name or 'Заказчик'}) обязательное для исполнения предписание об устранении допущенных нарушений законодательства путем внесения изменений в извещение и электронные документы закупки и продления срока подачи заявок в установленном законом порядке.",
        ]

        # Приложения
        attachments = [
            f"1. Копия извещения об осуществлении закупки №{summary.notice_number} из ЕИС.",
            "2. Выписка из Технического задания (Описания объекта закупки).",
            "3. Выписка из проекта государственного контракта.",
            "4. Документы, подтверждающие правоспособность Заявителя (выписка из ЕГРЮЛ/ЕГРИП).",
        ]

        today_str = datetime.date.today().strftime("%d.%m.%Y")

        return FASComplaint(
            fas_authority_name=fas_name,
            fas_address=fas_addr,
            applicant_name=app_name,
            applicant_inn=applicant_inn or "Указывается Заявителем",
            applicant_contacts=applicant_contacts or "info@supplier.ru / +7 (000) 000-00-00",
            customer_name=summary.customer_name or "Заказчик",
            customer_inn=summary.customer_inn or "Н/Д",
            customer_kpp=summary.customer_kpp or "Н/Д",
            customer_address=summary.customer_address or "По данным ЕИС",
            etp_name=summary.etp_name or "ЭТП ЕИС",
            notice_number=summary.notice_number or "Н/Д",
            purchase_subject=summary.purchase_subject or "Поставка медицинских изделий",
            nmck_formatted=nmck_text,
            episodes=episodes,
            petitum=petitum,
            attachments=attachments,
            created_date=today_str,
        )
